using System.Buffers.Binary;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using Npgsql;
using NpgsqlTypes;

[assembly: System.Runtime.CompilerServices.InternalsVisibleTo("Shorepop.Verifier.Tests")]

namespace Shorepop.Verifier;

/// <summary>
/// Durable shared settlement ledger in the dedicated shorepop_verifier schema. Schema creation and
/// role provisioning belong to deployment, not the app. Every mutation takes the same per-app
/// PostgreSQL transaction advisory lock. This intentionally serializes settlements within an app:
/// claim-group limits, ownership transfers, acknowledgments and entitlement revisions remain atomic
/// even when requests hit different processes. Read-only queries see a committed snapshot.
/// </summary>
public sealed class PostgresPurchaseStore : IPurchaseStore
{
    private readonly string connectionString;
    private readonly long subscriptionRevisionEpoch;
    public string Kind => "postgres";

    public PostgresPurchaseStore(string databaseUrlOrConnectionString, long subscriptionRevisionEpoch = 0)
    {
        if (subscriptionRevisionEpoch < 0 || subscriptionRevisionEpoch == long.MaxValue)
            throw new ArgumentOutOfRangeException(nameof(subscriptionRevisionEpoch));
        this.subscriptionRevisionEpoch = subscriptionRevisionEpoch;
        connectionString = NormalizeConnectionString(databaseUrlOrConnectionString);
        using var connection = Open();
        using var tx = connection.BeginTransaction();
        Lock(connection, tx, "schema", "v1");
        Execute(connection, tx, """
            CREATE TABLE IF NOT EXISTS shorepop_verifier.purchases(
              store TEXT NOT NULL, app_id TEXT NOT NULL, transaction_id TEXT NOT NULL, player_id TEXT NOT NULL,
              product_id TEXT NOT NULL, environment TEXT NOT NULL, refunded BOOLEAN NOT NULL, expiry_ticks BIGINT NOT NULL,
              original_ref TEXT NULL, signed_payload TEXT NULL, signed_date_ms BIGINT NOT NULL,
              created_utc TEXT NOT NULL, updated_utc TEXT NOT NULL,
              PRIMARY KEY(store, app_id, transaction_id));
            ALTER TABLE shorepop_verifier.purchases ADD COLUMN IF NOT EXISTS revenue_verified BOOLEAN NOT NULL DEFAULT FALSE;
            ALTER TABLE shorepop_verifier.purchases ADD COLUMN IF NOT EXISTS gross_revenue_micros BIGINT NOT NULL DEFAULT 0;
            ALTER TABLE shorepop_verifier.purchases ADD COLUMN IF NOT EXISTS revenue_currency TEXT NOT NULL DEFAULT '';
            ALTER TABLE shorepop_verifier.purchases ADD COLUMN IF NOT EXISTS revenue_transaction_id TEXT NOT NULL DEFAULT '';
            ALTER TABLE shorepop_verifier.purchases ADD COLUMN IF NOT EXISTS revenue_purchased_at_unix_ms BIGINT NOT NULL DEFAULT 0;
            ALTER TABLE shorepop_verifier.purchases ADD COLUMN IF NOT EXISTS revenue_refunded BOOLEAN NOT NULL DEFAULT FALSE;
            ALTER TABLE shorepop_verifier.purchases ADD COLUMN IF NOT EXISTS refunded_revenue_order_ids_json TEXT NOT NULL DEFAULT '[]';
            CREATE INDEX IF NOT EXISTS purchases_original ON shorepop_verifier.purchases(store, app_id, original_ref);
            CREATE TABLE IF NOT EXISTS shorepop_verifier.claims(
              seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              store TEXT NOT NULL, app_id TEXT NOT NULL, transaction_id TEXT NOT NULL, player_id TEXT NOT NULL,
              created_utc TEXT NOT NULL, acked_utc TEXT NULL,
              UNIQUE(store, app_id, transaction_id, player_id),
              FOREIGN KEY(store, app_id, transaction_id) REFERENCES shorepop_verifier.purchases(store, app_id, transaction_id));
            CREATE INDEX IF NOT EXISTS claims_player ON shorepop_verifier.claims(player_id, store, app_id);
            CREATE TABLE IF NOT EXISTS shorepop_verifier.subscriptions(
              player_id TEXT NOT NULL, store TEXT NOT NULL, app_id TEXT NOT NULL, revision BIGINT NOT NULL, expiry_ticks BIGINT NOT NULL,
              PRIMARY KEY(player_id, store, app_id));
            CREATE TABLE IF NOT EXISTS shorepop_verifier.transfers(
              seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              store TEXT NOT NULL, app_id TEXT NOT NULL, transaction_id TEXT NOT NULL,
              from_player TEXT NOT NULL, to_player TEXT NOT NULL, reason TEXT NOT NULL, created_utc TEXT NOT NULL,
              FOREIGN KEY(store, app_id, transaction_id) REFERENCES shorepop_verifier.purchases(store, app_id, transaction_id));
            """);
        tx.Commit();
    }

    // Database URLs are common in hosting-provider environments; Npgsql itself expects key/value
    // connection strings. Do not include the supplied value or an inner exception in parse failures.
    internal static string NormalizeConnectionString(string value)
    {
        try
        {
            NpgsqlConnectionStringBuilder builder;
            if (value.StartsWith("postgres://", StringComparison.OrdinalIgnoreCase) ||
                value.StartsWith("postgresql://", StringComparison.OrdinalIgnoreCase))
            {
                var uri = new Uri(value);
                string[] auth = uri.UserInfo.Split(':', 2);
                if (auth.Length != 2 || string.IsNullOrEmpty(uri.Host) || uri.AbsolutePath.Length <= 1 || uri.Fragment.Length > 0)
                    throw new FormatException();
                builder = new NpgsqlConnectionStringBuilder
                {
                    Host = uri.Host, Port = uri.IsDefaultPort ? 5432 : uri.Port,
                    Database = Uri.UnescapeDataString(uri.AbsolutePath[1..]),
                    Username = Uri.UnescapeDataString(auth[0]), Password = Uri.UnescapeDataString(auth[1]),
                    SslMode = SslMode.VerifyFull,
                };
                foreach (string item in uri.Query.TrimStart('?').Split('&', StringSplitOptions.RemoveEmptyEntries))
                {
                    string[] pair = item.Split('=', 2);
                    if (pair.Length != 2) throw new FormatException();
                    string option = Uri.UnescapeDataString(pair[0]).ToLowerInvariant();
                    string setting = Uri.UnescapeDataString(pair[1]);
                    switch (option)
                    {
                        case "sslmode": builder.SslMode = Enum.Parse<SslMode>(setting.Replace("-", ""), true); break;
                        case "connect_timeout": builder.Timeout = int.Parse(setting, CultureInfo.InvariantCulture); break;
                        case "application_name": builder.ApplicationName = setting; break;
                        default: throw new FormatException();
                    }
                }
            }
            else builder = new NpgsqlConnectionStringBuilder(value);
            if (string.IsNullOrWhiteSpace(builder.Host) || string.IsNullOrWhiteSpace(builder.Database) || string.IsNullOrWhiteSpace(builder.Username))
                throw new FormatException();
            builder.IncludeErrorDetail = false;
            builder.LogParameters = false;
            builder.PersistSecurityInfo = false;
            // SQL is always schema-qualified and session pooling always resets state.
            builder.SearchPath = "pg_catalog";
            builder.NoResetOnClose = false;
            builder.MaxPoolSize = Math.Min(builder.MaxPoolSize, 4);
            builder.Timeout = builder.Timeout == 0 ? 10 : Math.Min(builder.Timeout, 10);
            builder.CommandTimeout = builder.CommandTimeout == 0 ? 15 : Math.Min(builder.CommandTimeout, 15);
            return builder.ConnectionString;
        }
        catch (Exception error) when (error is ArgumentException or FormatException or OverflowException)
        {
            throw new ArgumentException("Invalid PostgreSQL connection configuration.");
        }
    }

    private NpgsqlConnection Open()
    {
        var connection = new NpgsqlConnection(connectionString);
        try { connection.Open(); return connection; }
        catch { connection.Dispose(); throw; }
    }

    internal static void Lock(NpgsqlConnection connection, NpgsqlTransaction tx, string store, string app)
    {
        // Length-prefixed identities avoid ambiguous pairs; a hash collision merely serializes more
        // work. SHA256 is stable between runtimes unlike string.GetHashCode(). Transaction disposal
        // releases this lock even on refusal, exceptions or process loss.
        string identity = "shorepop_verifier:" + store.Length.ToString(CultureInfo.InvariantCulture) + ":" + store + app;
        long key = BinaryPrimitives.ReadInt64BigEndian(SHA256.HashData(Encoding.UTF8.GetBytes(identity)));
        Execute(connection, tx, "SELECT pg_advisory_xact_lock(@key)", ("key", key));
    }

    public BindResult Bind(PurchaseRecord record, DateTimeOffset now, Func<ClaimContext, ClaimDecision> decide)
    {
        using var connection = Open();
        using var tx = connection.BeginTransaction();
        Lock(connection, tx, record.Store, record.ApplicationId);
        var existing = Read(connection, tx, "WHERE p.store=@s AND p.app_id=@a AND p.transaction_id=@t",
            ("s", record.Store), ("a", record.ApplicationId), ("t", record.TransactionId)).FirstOrDefault();
        var current = ClaimList(connection, tx, record.Store, record.ApplicationId, record.TransactionId);
        string group = record.OriginalRef ?? existing?.OriginalRef ?? record.TransactionId;
        var groupClaimants = new List<string>();
        using (var command = Command(connection, tx, """
            SELECT c.player_id FROM shorepop_verifier.claims c JOIN shorepop_verifier.purchases p
              ON c.store=p.store AND c.app_id=p.app_id AND c.transaction_id=p.transaction_id
            WHERE p.store=@s AND p.app_id=@a AND COALESCE(p.original_ref,p.transaction_id)=@g
            GROUP BY c.player_id ORDER BY MIN(c.seq)
            """, ("s", record.Store), ("a", record.ApplicationId), ("g", group)))
        {
            using var reader = command.ExecuteReader();
            while (reader.Read()) groupClaimants.Add(reader.GetString(0));
        }
        long latest;
        using (var command = Command(connection, tx, """
            SELECT COALESCE(MAX(signed_date_ms),0) FROM shorepop_verifier.purchases
            WHERE store=@s AND app_id=@a AND COALESCE(original_ref,transaction_id)=@g
            """, ("s", record.Store), ("a", record.ApplicationId), ("g", group)))
            latest = Convert.ToInt64(command.ExecuteScalar());
        var previous = current.Select(c => c.PlayerId).ToList();
        var decision = decide(new ClaimContext(existing != null, current, groupClaimants, latest));
        if (decision.Action == ClaimAction.Refuse) { tx.Commit(); return new BindResult(decision, previous); }

        var row = existing == null ? record : StoreRules.Merge(existing, record);
        string stamp = Stamp(now);
        Execute(connection, tx, """
            INSERT INTO shorepop_verifier.purchases(store,app_id,transaction_id,player_id,product_id,environment,refunded,expiry_ticks,
              original_ref,signed_payload,signed_date_ms,created_utc,updated_utc,revenue_verified,gross_revenue_micros,
              revenue_currency,revenue_transaction_id,revenue_purchased_at_unix_ms,revenue_refunded,refunded_revenue_order_ids_json)
            VALUES(@s,@a,@t,@p,@prod,@env,@ref,@exp,@orig,@payload,@sd,@now,@now,@rv,@rm,@rc,@rt,@rd,@rr,@rh)
            ON CONFLICT(store,app_id,transaction_id) DO UPDATE SET environment=@env,refunded=@ref,expiry_ticks=@exp,
              original_ref=@orig,signed_payload=@payload,signed_date_ms=@sd,updated_utc=@now,
              revenue_verified=@rv,gross_revenue_micros=@rm,revenue_currency=@rc,revenue_transaction_id=@rt,revenue_purchased_at_unix_ms=@rd,
              revenue_refunded=@rr,refunded_revenue_order_ids_json=@rh
            """, ("s", row.Store), ("a", row.ApplicationId), ("t", row.TransactionId), ("p", row.PlayerId), ("prod", row.ProductId),
            ("env", row.Environment), ("ref", row.Refunded), ("exp", row.PurchasedPeriodExpiryUtcTicks),
            ("orig", row.OriginalRef), ("payload", row.SignedPayload), ("sd", row.SignedDateUnixMs), ("now", stamp),
            ("rv", row.RevenueVerified), ("rm", row.GrossRevenueMicros), ("rc", row.RevenueCurrency),
            ("rt", row.RevenueTransactionId), ("rd", row.RevenuePurchasedAtUnixMs), ("rr", row.RevenueRefunded), ("rh", row.RefundedRevenueOrderIdsJson));
        if (decision.Action == ClaimAction.Transfer)
        {
            foreach (var gone in current.Where(c => c.PlayerId != record.PlayerId))
                Execute(connection, tx, """
                    INSERT INTO shorepop_verifier.transfers(store,app_id,transaction_id,from_player,to_player,reason,created_utc)
                    VALUES(@s,@a,@t,@f,@p,@r,@now)
                    """, ("s", row.Store), ("a", row.ApplicationId), ("t", row.TransactionId), ("f", gone.PlayerId),
                    ("p", record.PlayerId), ("r", decision.Reason ?? ""), ("now", stamp));
            Execute(connection, tx, "DELETE FROM shorepop_verifier.claims WHERE store=@s AND app_id=@a AND transaction_id=@t AND player_id<>@p",
                ("s", row.Store), ("a", row.ApplicationId), ("t", row.TransactionId), ("p", record.PlayerId));
            Execute(connection, tx, "UPDATE shorepop_verifier.purchases SET player_id=@p WHERE store=@s AND app_id=@a AND transaction_id=@t",
                ("s", row.Store), ("a", row.ApplicationId), ("t", row.TransactionId), ("p", record.PlayerId));
        }
        Execute(connection, tx, """
            INSERT INTO shorepop_verifier.claims(store,app_id,transaction_id,player_id,created_utc) VALUES(@s,@a,@t,@p,@now)
            ON CONFLICT(store,app_id,transaction_id,player_id) DO NOTHING
            """, ("s", row.Store), ("a", row.ApplicationId), ("t", row.TransactionId), ("p", record.PlayerId), ("now", stamp));
        tx.Commit();
        return new BindResult(decision, previous);
    }

    public AckOutcome Ack(string store, string applicationId, string transactionId, string playerId, DateTimeOffset now)
    {
        using var connection = Open();
        using var tx = connection.BeginTransaction();
        Lock(connection, tx, store, applicationId);
        var claims = ClaimList(connection, tx, store, applicationId, transactionId);
        if (claims.Count == 0) { tx.Commit(); return AckOutcome.NotFound; }
        if (claims.All(c => c.PlayerId != playerId)) { tx.Commit(); return AckOutcome.NotClaimant; }
        Execute(connection, tx, """
            UPDATE shorepop_verifier.claims SET acked_utc=COALESCE(acked_utc,@now)
            WHERE store=@s AND app_id=@a AND transaction_id=@t AND player_id=@p
            """, ("s", store), ("a", applicationId), ("t", transactionId), ("p", playerId), ("now", Stamp(now)));
        tx.Commit();
        return AckOutcome.Acked;
    }

    public IReadOnlyList<PurchaseRecord> List(string playerId, string store, string applicationId)
    {
        using var connection = Open();
        return ClaimedBy(connection, null, playerId, store, applicationId);
    }

    public IReadOnlyList<string> Claimants(string store, string applicationId, string transactionId) =>
        Claims(store, applicationId, transactionId).Select(c => c.PlayerId).ToList();

    public IReadOnlyList<ClaimInfo> Claims(string store, string applicationId, string transactionId)
    {
        using var connection = Open();
        return ClaimList(connection, null, store, applicationId, transactionId);
    }

    public IReadOnlyList<TransferRecord> Transfers(string store, string applicationId, string transactionId)
    {
        using var connection = Open();
        using var command = Command(connection, null, """
            SELECT from_player,to_player,reason,created_utc FROM shorepop_verifier.transfers
            WHERE store=@s AND app_id=@a AND transaction_id=@t ORDER BY seq
            """, ("s", store), ("a", applicationId), ("t", transactionId));
        using var reader = command.ExecuteReader();
        var list = new List<TransferRecord>();
        while (reader.Read()) list.Add(new TransferRecord(reader.GetString(0), reader.GetString(1), reader.GetString(2), ParseStamp(reader.GetString(3))));
        return list;
    }

    public (long Revision, long CurrentExpiryUtcTicks) Subscription(string playerId, string store, string applicationId)
    {
        using var connection = Open();
        using var tx = connection.BeginTransaction();
        Lock(connection, tx, store, applicationId);
        long aggregate = StoreRules.Aggregate(ClaimedBy(connection, tx, playerId, store, applicationId));
        long revision = 0, expiry = 0;
        using (var command = Command(connection, tx, "SELECT revision,expiry_ticks FROM shorepop_verifier.subscriptions WHERE player_id=@p AND store=@s AND app_id=@a",
            ("p", playerId), ("s", store), ("a", applicationId)))
        {
            using var reader = command.ExecuteReader();
            if (reader.Read()) { revision = reader.GetInt64(0); expiry = reader.GetInt64(1); }
        }
        if (revision == 0 || expiry != aggregate)
        {
            revision = revision == 0 ? Math.Max(1, subscriptionRevisionEpoch) : checked(revision + 1);
            expiry = aggregate;
            Execute(connection, tx, """
                INSERT INTO shorepop_verifier.subscriptions(player_id,store,app_id,revision,expiry_ticks) VALUES(@p,@s,@a,@r,@e)
                ON CONFLICT(player_id,store,app_id) DO UPDATE SET revision=@r,expiry_ticks=@e
                """, ("p", playerId), ("s", store), ("a", applicationId), ("r", revision), ("e", expiry));
        }
        tx.Commit();
        return (revision, expiry);
    }

    private static List<PurchaseRecord> ClaimedBy(NpgsqlConnection connection, NpgsqlTransaction? tx, string playerId, string store, string app) =>
        Read(connection, tx, """
            WHERE p.store=@s AND p.app_id=@a AND EXISTS(SELECT 1 FROM shorepop_verifier.claims c
              WHERE c.store=p.store AND c.app_id=p.app_id AND c.transaction_id=p.transaction_id AND c.player_id=@p)
            ORDER BY p.transaction_id COLLATE "C"
            """, ("s", store), ("a", app), ("p", playerId)).Select(r => r with { PlayerId = playerId }).ToList();

    private static List<PurchaseRecord> Read(NpgsqlConnection connection, NpgsqlTransaction? tx, string where, params (string, object?)[] args)
    {
        using var command = Command(connection, tx, """
            SELECT p.store,p.app_id,p.transaction_id,p.player_id,p.product_id,p.environment,p.refunded,p.expiry_ticks,
              p.original_ref,p.signed_payload,p.signed_date_ms,p.revenue_verified,p.gross_revenue_micros,
              p.revenue_currency,p.revenue_transaction_id,p.revenue_purchased_at_unix_ms,p.revenue_refunded,p.refunded_revenue_order_ids_json
              FROM shorepop_verifier.purchases p
            """ + " " + where, args);
        using var reader = command.ExecuteReader();
        var list = new List<PurchaseRecord>();
        while (reader.Read()) list.Add(new PurchaseRecord(reader.GetString(0), reader.GetString(1), reader.GetString(2), reader.GetString(3),
            reader.GetString(4), reader.GetString(5), reader.GetBoolean(6), reader.GetInt64(7), reader.IsDBNull(8) ? null : reader.GetString(8),
            reader.IsDBNull(9) ? null : reader.GetString(9), reader.GetInt64(10), reader.GetBoolean(11), reader.GetInt64(12),
            reader.GetString(13), reader.GetString(14), reader.GetInt64(15), reader.GetBoolean(16), reader.GetString(17)));
        return list;
    }

    private static List<ClaimInfo> ClaimList(NpgsqlConnection connection, NpgsqlTransaction? tx, string store, string app, string transaction)
    {
        using var command = Command(connection, tx, """
            SELECT player_id,created_utc,acked_utc FROM shorepop_verifier.claims
            WHERE store=@s AND app_id=@a AND transaction_id=@t ORDER BY seq
            """, ("s", store), ("a", app), ("t", transaction));
        using var reader = command.ExecuteReader();
        var list = new List<ClaimInfo>();
        while (reader.Read()) list.Add(new ClaimInfo(reader.GetString(0), ParseStamp(reader.GetString(1)), reader.IsDBNull(2) ? null : ParseStamp(reader.GetString(2))));
        return list;
    }

    private static NpgsqlCommand Command(NpgsqlConnection connection, NpgsqlTransaction? tx, string sql, params (string, object?)[] args)
    {
        var command = new NpgsqlCommand(sql, connection, tx);
        foreach (var (name, value) in args)
        {
            // All nullable fields in this store are text. Explicit typing also handles first binds
            // with no signed payload/original reference, for which inference from null is impossible.
            if (value == null) command.Parameters.AddWithValue(name, NpgsqlDbType.Text, DBNull.Value);
            else command.Parameters.AddWithValue(name, value);
        }
        return command;
    }

    private static void Execute(NpgsqlConnection connection, NpgsqlTransaction? tx, string sql, params (string, object?)[] args)
    {
        using var command = Command(connection, tx, sql, args);
        command.ExecuteNonQuery();
    }

    private static string Stamp(DateTimeOffset time) => time.UtcDateTime.ToString("O", CultureInfo.InvariantCulture);
    private static DateTimeOffset ParseStamp(string text) => DateTimeOffset.Parse(text, CultureInfo.InvariantCulture,
        DateTimeStyles.AssumeUniversal | DateTimeStyles.AdjustToUniversal);
}
