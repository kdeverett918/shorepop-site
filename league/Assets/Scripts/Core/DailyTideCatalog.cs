using System;
using System.Collections.Generic;
using System.Globalization;

namespace BloomHarbor
{
    [Serializable]
    public sealed class DailyTideChallenge
    {
        public int RuleVersion, RecipeId;
        public uint Seed;
        public string DateKey;
        public LevelDefinition Level;
    }

    /// <summary>Pure, versioned Daily Tide recipes. The caller supplies UTC; no clock or player state is read.</summary>
    public static class DailyTideCatalog
    {
        // Version 3 is the score-target rule set. Version 2 boards are deliberately not
        // reconstructable: their win condition no longer exists, so a saved v2 daily is refused.
        public const int RuleVersion = 3;
        public const int LegacyRuleVersion = 1;
        public const int LegacyRecipeId = 0;
        public const int RecipeCount = 7;
        // Solver-calibrated score targets per recipe id 1..7, plus the frozen legacy board.
        // Generated by `dotnet run --project tests/daily/DailyTests.csproj -- --calibrate`.
        private static readonly int[] RecipeTargets = { 2618, 6881, 3463, 1554, 2090, 4409, 2390 };
        public const int LegacyTargetScore = 3018;
        // This Monday is the permanent start of the seven-day cycle, not the current date.
        private static readonly DateTime CycleAnchor = new DateTime(2026, 9, 7, 0, 0, 0, DateTimeKind.Utc);
        private static readonly string[] RecipeNames = {
            "Color currents", "Crossing rocket lanes", "Frosted coves", "The bound-crate stair",
            "Windowbox tides", "Weave the tide", "A meeting of specials"
        };

        public static LevelDefinition Get(DateTime utcDate, int ruleVersion = RuleVersion)
        { return Describe(utcDate, ruleVersion).Level; }

        public static DailyTideChallenge Describe(DateTime utcDate, int ruleVersion = RuleVersion)
        {
            DateTime day = UtcDay(utcDate);
            int recipeId = ruleVersion == LegacyRuleVersion ? LegacyRecipeId : GetRecipeId(day);
            uint seed = GetSeed(day, ruleVersion);
            return new DailyTideChallenge { RuleVersion = ruleVersion, RecipeId = recipeId, Seed = seed,
                DateKey = day.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture),
                Level = CreateRecipe(recipeId, seed, ruleVersion) };
        }

        public static int GetRecipeId(DateTime utcDate)
        {
            long days = (UtcDay(utcDate).Ticks - CycleAnchor.Ticks) / TimeSpan.TicksPerDay;
            return (int)((days % RecipeCount + RecipeCount) % RecipeCount) + 1;
        }

        public static uint GetSeed(DateTime utcDate, int ruleVersion = RuleVersion)
        {
            DateTime day = UtcDay(utcDate);
            if (ruleVersion == LegacyRuleVersion) return (uint)(day.Year * 1000 + day.DayOfYear + 77331);
            if (ruleVersion != RuleVersion) throw new ArgumentOutOfRangeException("ruleVersion", "Unsupported Daily Tide rules.");
            string key = "BloomHarbor/DailyTide/v3/" + day.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture);
            uint hash = 2166136261u;
            unchecked { foreach (char character in key) { hash ^= character; hash *= 16777619u; } }
            return hash == 0 ? 0xD41D8CD9u : hash;
        }

        public static string GetRecipeName(int recipeId)
        {
            if (recipeId == LegacyRecipeId) return "Daily tide (legacy)";
            if (recipeId < 1 || recipeId > RecipeCount) throw new ArgumentOutOfRangeException("recipeId");
            return RecipeNames[recipeId - 1];
        }

        // Reconstruct a stored challenge using its saved version/recipe/seed, independently of today's date.
        public static LevelDefinition CreateRecipe(int recipeId, uint seed, int ruleVersion = RuleVersion)
        {
            if (seed == 0) throw new ArgumentOutOfRangeException("seed", "A Daily Tide seed must be nonzero.");
            if (ruleVersion == LegacyRuleVersion)
            {
                if (recipeId != LegacyRecipeId) throw new ArgumentOutOfRangeException("recipeId", "Legacy dailies use recipe zero.");
                return CreateLegacy(seed);
            }
            if (ruleVersion != RuleVersion) throw new ArgumentOutOfRangeException("ruleVersion", "Unsupported Daily Tide rules.");
            if (recipeId < 1 || recipeId > RecipeCount) throw new ArgumentOutOfRangeException("recipeId");
            var level = new LevelDefinition { Id = 0, Chapter = 0,
                Name = RecipeNames[recipeId - 1], Seed = seed, ColorCount = recipeId >= 5 && recipeId != 6 ? 5 : 4,
                BreezeEnabled = true, Moves = 30, TargetScore = RecipeTargets[recipeId - 1] };
            switch (recipeId)
            {
                case 1: OpenColors(level); break;
                case 2: RocketLanes(level); break;
                case 3: ProtectedIce(level); break;
                case 4: TwoHitRouting(level); break;
                case 5: MixedWindows(level); break;
                case 6: BreezeWeave(level); break;
                case 7: CombinationMeeting(level); break;
            }
            return level;
        }

        public static LevelDefinition CreateLegacy(DateTime utcDate)
        { return CreateLegacy(GetSeed(utcDate, LegacyRuleVersion)); }

        // Frozen version-one level-14 definition. Do not read the evolving campaign catalog here.
        public static LevelDefinition CreateLegacy(uint seed)
        {
            if (seed == 0) throw new ArgumentOutOfRangeException("seed");
            var level = new LevelDefinition { Id = 0, Chapter = 2, Name = "Daily tide",
                Seed = seed, ColorCount = 4, Moves = 30, BreezeEnabled = true, TargetScore = LegacyTargetScore,
                Introduction = "One shared seed. A fresh little challenge." };
            // Mirror order matches the old chapter-two level-14 factory exactly.
            AddIce(level, new[] { 4,2, 3,2, 4,3, 3,3, 4,5, 3,5 });
            return level;
        }

        private static DateTime UtcDay(DateTime date)
        {
            if (date.Kind == DateTimeKind.Local)
                throw new ArgumentException("Pass UTC or an explicitly UTC calendar date; core does not apply a machine time zone.", "date");
            return new DateTime(date.Year, date.Month, date.Day, 0, 0, 0, DateTimeKind.Utc);
        }

        private static void OpenColors(LevelDefinition level)
        {
            level.Moves = 24;
            level.Introduction = "Two colors, an open board. Choose which groups to grow before you clear them.";
            level.InitialColors = new int[72];
            int offset = (int)(level.Seed % 4);
            for (int y = 0; y < 9; y++) for (int x = 0; x < 8; x++)
                level.InitialColors[y * 8 + x] = (x / 2 + y / 2 + offset) % 4;
            Paint(level, 0, new[] { 0,0, 1,0, 0,1, 1,1 });
            Paint(level, 2, new[] { 6,7, 7,7, 6,8, 7,8 });
        }

        private static void RocketLanes(LevelDefinition level)
        {
            level.Moves = 32;
            level.Introduction = "Two groups can make rockets. Preview their direction and aim through the crossing crate lanes.";
            Fill(level, new[] { 2, 3 });
            Paint(level, 0, new[] { 2,0, 3,0, 4,0, 2,1, 3,1 });
            Paint(level, 1, new[] { 0,3, 1,3, 0,4, 1,4, 0,5 });
            AddCrates(level, 1, new[] { 3,3, 4,3, 5,3, 6,3, 7,3, 3,4, 3,5, 3,6 });
        }

        private static void ProtectedIce(LevelDefinition level)
        {
            level.Moves = 34;
            level.Introduction = "The frost sits behind crates. Open a route, then clear the iced tiles themselves.";
            Fill(level, new[] { 1, 3 });
            AddCrates(level, 1, new[] { 1,3, 1,4, 2,2, 3,2, 4,5, 4,6, 5,4, 6,4 });
            int[] frost = { 2,3, 3,3, 2,4, 3,4, 5,5, 6,5, 5,6, 6,6 };
            AddIce(level, frost);
            for (int i = 0; i < frost.Length; i += 2) level.InitialColors[frost[i + 1] * 8 + frost[i]] = (frost[i] + frost[i + 1]) % 2 == 0 ? 2 : 0;
            Paint(level, 2, new[] { 0,1, 1,1, 2,1, 0,2, 1,2, 0,3, 0,4 });
        }

        private static void TwoHitRouting(LevelDefinition level)
        {
            level.Moves = 38;
            level.Introduction = "Bound crates need two separate hits. Follow the stair and plan where your specials will land.";
            Fill(level, new[] { 1, 2, 3 });
            Paint(level, 0, new[] { 0,0, 1,0, 2,0, 0,1, 1,1, 2,1, 0,2 });
            AddCrates(level, 2, new[] { 2,2, 3,2, 3,3, 4,3, 4,4, 5,4, 5,5, 6,5, 6,6, 5,6 });
        }

        private static void MixedWindows(LevelDefinition level)
        {
            level.Moves = 40;
            level.Introduction = "Some windows are frosted; others are boxed in. Balance direct clears with a second hit on bound crates.";
            Fill(level, new[] { 0, 1, 2, 4 });
            Paint(level, 3, new[] { 0,6, 1,6, 2,6, 0,7, 1,7, 2,7, 0,8, 1,8, 2,8 });
            AddCrates(level, 1, new[] { 1,2, 5,2, 2,5, 6,5 });
            AddCrates(level, 2, new[] { 3,2, 6,2, 1,5, 4,5 });
            AddIce(level, new[] { 0,4, 2,4, 4,4, 6,4, 0,7, 2,7, 4,7, 7,7 });
        }

        private static void BreezeWeave(LevelDefinition level)
        {
            level.Moves = 26;
            level.InitialBreezeCharge = 20;
            level.Introduction = "One Breeze is charged for this tide. Preview both weaves to connect the frosted pairs around the posts.";
            Fill(level, new[] { 0, 1, 3 });
            for (int y = 1; y <= 5; y++)
            {
                int start = y % 2 == 0 ? 1 : 3;
                Paint(level, 2, new[] { start,y, start+1,y });
            }
            AddCrates(level, 1, new[] { 5,2, 5,4, 5,6 });
            AddIce(level, new[] { 1,2, 2,2, 3,3, 4,3 });
        }

        private static void CombinationMeeting(LevelDefinition level)
        {
            level.Moves = 34;
            level.Introduction = "Make a rocket beside a bomb. Tap the pair for a wider blast through the far-side blockers.";
            Fill(level, new[] { 2, 3, 4 });
            Paint(level, 0, new[] { 0,0, 1,0, 2,0, 0,1, 1,1 });
            Paint(level, 1, new[] { 3,0, 4,0, 5,0, 3,1, 4,1, 5,1, 3,2 });
            AddCrates(level, 1, new[] { 1,4, 2,4, 3,4, 4,4, 5,4, 6,4 });
            AddIce(level, new[] { 2,6, 3,6, 4,6, 5,6 });
        }

        private static void Fill(LevelDefinition level, int[] palette)
        {
            level.InitialColors = new int[72];
            int offset = (int)(level.Seed % (uint)palette.Length);
            for (int y = 0; y < 9; y++) for (int x = 0; x < 8; x++)
                level.InitialColors[y * 8 + x] = palette[(x + y + offset) % palette.Length];
        }

        private static void Paint(LevelDefinition level, int color, int[] xy)
        { for (int i = 0; i < xy.Length; i += 2) level.InitialColors[xy[i + 1] * 8 + xy[i]] = color; }

        private static void AddCrates(LevelDefinition level, int hp, int[] xy)
        { for (int i = 0; i < xy.Length; i += 2) level.Blockers.Add(new BlockerDefinition(xy[i], xy[i + 1], hp, 0)); }

        private static void AddIce(LevelDefinition level, int[] xy)
        { for (int i = 0; i < xy.Length; i += 2) level.Blockers.Add(new BlockerDefinition(xy[i], xy[i + 1], 0, 1)); }
    }
}
