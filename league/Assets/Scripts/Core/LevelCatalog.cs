        /// (design/specs/board-mechanics-r16.md, calibration table).</summary>
        public static int DropCount(int levelId)
        {
            if (ObjectiveOf(levelId) != LevelObjective.Drop) return 0;
            int world = WorldOf(levelId), stage = StageOf(levelId);
