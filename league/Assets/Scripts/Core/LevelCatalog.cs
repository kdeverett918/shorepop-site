                Seed = source.Seed, TargetScore = source.TargetScore, BreezeEnabled = source.BreezeEnabled,
                InitialBreezeCharge = source.InitialBreezeCharge,
                Introduction = IntroductionFor(WorldOf(levelId), StageOf(levelId))
            };
            // Rule v4 predates the toy curriculum. Keep its original first-coast recipes.
            if (world == 1)
            {
                int[] targets = {14545,10390,10480,10090,909,2727,9145,8800,7954,8027,2290,6209};
                original.TargetScore = targets[stage-1];
                // The recipe keeps the tutorial budgets it was frozen with (the campaign's were retuned
                // 2026-11-25, owner "levels seem too short"): a daily board never changes under a player.
                original.Moves = MovesFor(world, stage, true);
                original.ColorCount = stage <= 4 ? 3 : 4;
                original.CreationTier = 3;
                original.BreezeEnabled = stage >= 5;
                original.InitialBreezeCharge = 0;
            }
            AddLayout(original, WorldOf(levelId), StageOf(levelId));
            AddCollectProps(original, WorldOf(levelId), StageOf(levelId));
            return original;
        }

