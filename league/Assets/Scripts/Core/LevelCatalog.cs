        private static void AuthorTutorial(LevelDefinition level, int id, int lessonColor)
        {
            level.InitialColors = new int[level.Width * level.Height];
            // The field the lesson sits in, drawn from the level's own seed and its own colour count.
            // It used to be a fixed (x / 2 + y / 2) % 3 checkerboard: every tile had a guaranteed
            // same-colour twin, so every tap was legal and no opening level ever needed a plan, and
            // stages 1-7, 12 and 20 all drew the identical board. The authored teaching island below
            // is unchanged -- only the field it reads against varies now.
            // Level 1 stays on the original checkerboard: it is a pinned fixture. tests/core
            // BreezeCurriculum asserts every one of its 72 cells, and the native AltTester lanes tap
            // fixed coordinates on it. Keeping it also leaves the very first board maximally readable,
            // and the monotony this fixes was stages 2-7 repeating it, not level 1 existing.
            // Level 20 is calibrated as a 0.95 breather against that same guaranteed-twin field, so it
            // keeps it too rather than have its authored target silently become a wall.
            bool pinned = level.Id == 1 || level.Id == 20;
            uint rng = level.Seed | 1u;
            int fieldColors = Math.Max(3, level.ColorCount);
            for (int y = 0; y < level.Height; y++) for (int x = 0; x < level.Width; x++)
            {
                if (pinned) { level.InitialColors[y * level.Width + x] = (x / 2 + y / 2) % 3; continue; }
                rng ^= rng << 13; rng ^= rng >> 17; rng ^= rng << 5;   // xorshift32, deterministic per level
                level.InitialColors[y * level.Width + x] = (int)(rng % (uint)fieldColors);
            }
            if (id == 1) return;
            int count = id == 2 ? 5 : id == 3 ? 7 : 9;
            int goalColor = lessonColor;
            // Isolated contiguous teaching island against two other colors, fully visible at the bottom.
            for (int y = 0; y < 4; y++) for (int x = 0; x < level.Width; x++)
                level.InitialColors[y * level.Width + x] = (goalColor + 1 + (x + y) % 2) % 3;
            int[] islandX = { 1, 2, 3, 1, 2, 3, 1, 2, 3 };
            int[] islandY = { 0, 0, 0, 1, 1, 1, 2, 2, 2 };
            for (int i = 0; i < count; i++) level.InitialColors[islandY[i] * level.Width + islandX[i]] = goalColor;
        }

        private static void AuthorBreezeLesson(LevelDefinition level, int id, int lessonColor)
        {
            level.InitialColors = new int[level.Width * level.Height];
            int goalColor = lessonColor;
            var otherColors = new List<int>();
            for (int color = 0; color < level.ColorCount; color++) if (color != goalColor) otherColors.Add(color);
            for (int y = 0; y < level.Height; y++) for (int x = 0; x < level.Width; x++)
                level.InitialColors[y * level.Width + x] = otherColors[(x + y * 2) % otherColors.Count];

            if (id == 5)
            {
                // Five separate pairs become a ten-tile prism group after a right weave.
                level.InitialBreezeCharge = 20;
                for (int y = 1; y <= 5; y++)
                {
                    int startX = y % 2 == 0 ? 2 : 4;
                    level.InitialColors[y * level.Width + startX] = goalColor;
                    level.InitialColors[y * level.Width + startX + 1] = goalColor;
                }
                return;
            }

            // Earn charge above the lower five-row exercise without dropping its paired tiles.
            // The two ten-tile islands are real ordinary groups; alternatives remain playable.
            for (int y = 4; y < level.Height; y++) for (int x = 0; x < level.Width; x++)
                level.InitialColors[y * level.Width + x] = 0;
            for (int y = 7; y <= 8; y++) for (int x = 3; x <= 7; x++) level.InitialColors[y * level.Width + x] = 2;
            for (int y = 5; y <= 6; y++) for (int x = 0; x <= 4; x++) level.InitialColors[y * level.Width + x] = 3;
            for (int y = 0; y <= 4; y++)
            {
                int startX = y % 2 == 0 ? 2 : 4;
                level.InitialColors[y * level.Width + startX] = goalColor;
                level.InitialColors[y * level.Width + startX + 1] = goalColor;
            }
        }

