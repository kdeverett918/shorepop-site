        /// <summary>
        /// The coast whose name in the live locale <paramref name="drawn"/> carries (case aside), or 0. QA
        /// reads a screen's text through it to prove the name on screen is the coast on screen.
        /// </summary>
        public static int CoastNamedIn(string drawn)
        {
            if (string.IsNullOrEmpty(drawn)) return 0;
            foreach (var coast in coasts)
                if (Carries(drawn, coast.DisplayName)) return coast.Id;
            return 0;
        }

        /// <summary>
        /// Why <paramref name="drawn"/> names a coast wrongly, or null when it does not: it carries a
        /// <see cref="RetiredCoastNames"/> entry, or a coast's name as another loaded locale writes it where
        /// the live locale writes it differently ("Candy Lagoon" in Spanish copy, which reads "Laguna de
        /// Caramelo"). The pseudolocale is not a language and is never compared.
        /// </summary>
        public static string CoastNameFault(string drawn)
        {
            if (string.IsNullOrEmpty(drawn)) return null;
            foreach (string retired in RetiredCoastNames)
                if (Carries(drawn, retired)) return "carries the retired coast name \"" + retired + "\"";
            foreach (var coast in coasts)
            {
                string live = coast.DisplayName;
                foreach (string locale in Strings.LoadedLocales)
                {
                    if (string.Equals(locale, Strings.PseudoLocale, StringComparison.OrdinalIgnoreCase)) continue;
                    if (!Strings.TryGetRaw(locale, coast.NameKey, out string other) || string.IsNullOrEmpty(other)) continue;
                    if (Carries(live, other) || !Carries(drawn, other)) continue;
                    return "carries coast " + coast.Id + "'s " + locale + " name \"" + other + "\"; the " + Strings.Locale + " name is \"" + live + "\"";
                }
            }
            return null;
        }

        static bool Carries(string text, string name)
        {
            return !string.IsNullOrEmpty(name) &&
                System.Globalization.CultureInfo.InvariantCulture.CompareInfo.IndexOf(text, name, System.Globalization.CompareOptions.IgnoreCase) >= 0;
        }

        /// <summary>The coast a campaign level belongs to: <see cref="LevelsPerCoast"/> levels each.</summary>
        public static CoastDefinition CoastFor(int levelId)
        {
            if (levelId < 1 || levelId > levels.Count) throw new ArgumentOutOfRangeException("levelId");
            return coasts[(levelId - 1) / LevelsPerCoast];
        }

        /// <summary>The coast this level belongs to, 1..5. The catalog's own word for a world.</summary>
        public static int WorldOf(int levelId) { return (levelId - 1) / LevelsPerCoast + 1; }
        /// <summary>The level's place inside its coast, 1..<see cref="LevelsPerCoast"/>.</summary>
        public static int StageOf(int levelId) { return (levelId - 1) % LevelsPerCoast + 1; }
        /// <summary>
        /// The level's permanent identity: its place in a full-size campaign, 1..300. Seeds, names
        /// and calibrated targets are all keyed to it, so a level is the same board whatever
        /// <see cref="LevelsPerCoast"/> currently is.
        /// </summary>
        public static int SlotOf(int levelId) { return (WorldOf(levelId) - 1) * FullLevelsPerCoast + StageOf(levelId); }
        /// <summary>The same authored board under the original twelve-stage campaign numbering.</summary>
        public static int FromLegacyLevelId(int legacyId)
        {
            if (legacyId < 1 || legacyId > LegacyLevelCount) throw new ArgumentOutOfRangeException("legacyId");
            return ((legacyId - 1) / LegacyLevelsPerCoast) * LevelsPerCoast + (legacyId - 1) % LegacyLevelsPerCoast + 1;
        }
        public static CoastDefinition Coast(int coastId)
        {
            if (coastId < 1 || coastId > coasts.Length) throw new ArgumentOutOfRangeException("coastId");
            return coasts[coastId - 1];
        }

