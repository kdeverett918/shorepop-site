                    var level = new LevelDefinition
                    {
                        Id = id, Chapter = world, Name = NameFor(names, world, stage, legacy),
                        // Keyed to the slot, not the id, so the flip to sixty per coast renumbers
                        // levels without changing a single board.
                        Seed = unchecked(0xB1000000u + (uint)(slot * 7919) + (!legacy && slot==28?1u:0u)),
                        ColorCount = legacy && world == 1 && stage >= 5 && stage <= 7 ? 4 : ColorsFor(world, stage),
                        CreationTier = legacy ? 3 : world == 1 ? stage < 4 ? 0 : stage < 12 ? 1 : stage < 20 ? 2 : 3 : 3,
                        Moves = MovesFor(world, stage) + (!legacy && ObjectiveFor(world, stage) == LevelObjective.Drop ? DropExtraMoves : 0),
                        BreezeEnabled = world > 1 || stage >= (legacy ? 5 : 28),
                        // The frozen legacy catalog keeps the rules its attempts began under.
                        WaveEnabled = !legacy && (world > 1 || stage >= WaveLessonLevel),
                        Introduction = IntroductionFor(world, stage)
                    };
                    AddLayout(level, world, stage);
                    AddCollectProps(level, world, stage);
                    // The lesson color used to be the first collection goal. It still selects the
                    // authored teaching islands; nothing about it decides winning any more.
                    int color = (stage - 1 + world - 1) % level.ColorCount;
                    level.TargetScore = legacy && slot <= LegacyOpeningTargets.Length ? LegacyOpeningTargets[slot - 1] : Targets[slot - 1];
                    if (legacy && world == 1 && stage <= 4) AuthorTutorial(level, stage, color);
                    if (legacy && world == 1 && (stage == 5 || stage == 6)) AuthorBreezeLesson(level, stage, color);
                    if (!legacy && world == 1 && stage <= 7) AuthorTutorial(level, stage == 4 ? 2 : 1, color);
                    // Rocket practice opens with its row rocket in place (design uplift S1 #7). Nothing
                    // else on the board moves: a placed special draws nothing from the seed.
                    if (!legacy && slot == RocketPracticeLevel)
                        level.Specials.Add(new SpecialPlacement(RocketPracticeX, RocketPracticeY, SpecialType.RocketH));
                    if (!legacy && world == 1 && (stage == 12 || stage == 20))
                    { level.Blockers.Clear(); AuthorTutorial(level, stage == 12 ? 3 : 4, color); }
                    if (!legacy && world == 1 && (stage == 28 || stage == 29))
                    { level.Blockers.Clear(); AuthorBreezeLesson(level, stage == 28 ? 5 : 6, 1); }
                    AddShellEncounter(level, world, stage);
                    // The legacy catalog is frozen: its attempts finish under the rules they began with.
                    if (!legacy) AddBoardMechanic(level, world, stage);
                    result.Add(level);
                }
            return result;
        }

        // ---- The curve (design/implementation/expansion-r1) ----

        /// <summary>True for the authored tutorial: world 1's first twelve stages, which keep every
        /// number they have always had and are the one part of the campaign that must not be lost.</summary>
        public static bool IsTutorial(int world, int stage) { return world == 1 && stage <= TutorialStages; }

        /// <summary>
        /// True for a gate: the tenth stage of every block of ten inside a coast, the hardest level
        /// of its block and the one a player is most likely to lose. The map plaque marks it so a
        /// loss there reads as the level being hard rather than the game misbehaving (owner
        /// feedback 2026-09-09). It is the single accessor everything reads; no caller carries an id,
        /// so the marker follows this curve through the flip to sixty stages per coast on its own.
        ///
        /// The stage that closes a coast is a gate too. That clause is doing real work only while
        /// <see cref="LevelsPerCoast"/> is committed at twelve; at sixty the closing stage is
        /// already a multiple of <see cref="GateInterval"/>.
        ///
        /// A tutorial stage is never a gate. World 1's first twelve levels sit off the difficulty
        /// curve at a measured win rate of 1.00, and a "tough level" marker on a level nobody loses
        /// would be a plaque telling the player something untrue.
        /// </summary>
        public static bool IsGateLevel(int levelId)
        {
            if (levelId < 1 || levelId > LevelCount) return false;
            int world = WorldOf(levelId), stage = StageOf(levelId);
            if (IsTutorial(world, stage) || (world == 1 && (stage == 20 || stage == 28 || stage == 29))) return false;
            return stage % GateInterval == 0 || stage == LevelsPerCoast;
        }

        /// <summary>True for the breather that opens a block, the level right after a gate.</summary>
        public static bool IsBreatherLevel(int levelId)
        {
            if (levelId < 1 || levelId > LevelCount) return false;
            int world = WorldOf(levelId), stage = StageOf(levelId);
            return !IsTutorial(world, stage) && stage > 1 && stage % GateInterval == 1;
        }

