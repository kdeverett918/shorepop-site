        // Three bounded score-only encounters. Shells obstruct paths, not the collect counter.
        private static void AddShellEncounter(LevelDefinition level, int world, int stage)
        {
            if (!((world == 1 && stage == 9) || ((world == 2 || world == 3) && stage == 4))) return;
            level.Introduction = "Shells need direct blasts. Rockets, bombs and Tide Sweep can open them.";
            if (world == 2) { AddShell(level, 4, 3); return; }
            if (world == 3) { AddShell(level, 6, 5); return; }
            AddShell(level, 2, 3);

            // A five-tile group reaches the shell, but merely clearing beside it does nothing.
            // Creating the seeded column rocket at (2,0), rather than at (1,0), aims the next
            // action through it. Every cell outside the teaching pocket keeps its seeded color.
            level.InitialColors = new int[level.Width * level.Height];
            for (int i = 0; i < level.InitialColors.Length; i++) level.InitialColors[i] = -1;
            for (int y = 0; y <= 3; y++) for (int x = 0; x <= 4; x++)
                level.InitialColors[y * level.Width + x] = 1 + (x + y) % (level.ColorCount - 1);
            int[] group = { 1,0, 2,0, 3,0, 2,1, 2,2 };
            for (int i = 0; i < group.Length; i += 2)
                level.InitialColors[group[i + 1] * level.Width + group[i]] = 0;
        }

